import {readFileSync,readdirSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const directory=resolve(root,'supabase/migrations');
const files=readdirSync(directory).filter(file=>/^\d+_[a-z0-9_]+\.sql$/.test(file)).sort();
if(!files.length)throw new Error('No migration files found.');
const versions=new Set();
let bundle=`-- Generated from supabase/migrations; do not edit this file directly.
-- FRESH PROJECT ONLY. First run 01_preflight.sql and review the result.
-- Run the ENTIRE file as postgres in Dashboard SQL Editor. Never select a fragment.
-- Any failure rolls back this batch. No DROP/reset of existing learning data.
begin;
set local lock_timeout='5s';
set local statement_timeout='120s';
select pg_advisory_xact_lock(hashtext('kotoba-dashboard-bootstrap'));
do $$begin
 if current_setting('server_version_num')::integer<150000 then raise exception 'PostgreSQL 15 or newer required';end if;
 if current_user<>'postgres' then raise exception 'Use the postgres SQL Editor role';end if;
 if (select count(*) from auth.users where lower(email)='yzh72339@gmail.com')>1 then raise exception 'Multiple matching Auth accounts: review identity before proceeding';end if;
 if exists(select 1 from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','p'))
    or to_regnamespace('private') is not null
    or exists(select 1 from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and not exists(select 1 from pg_catalog.pg_depend d where d.classid='pg_proc'::regclass and d.objid=p.oid and d.deptype='e'))
    or exists(select 1 from pg_catalog.pg_trigger where tgrelid='auth.users'::regclass and not tgisinternal) then
  raise exception 'Existing database objects detected: stop and review migration history; never reset/delete them';
 end if;
end;$$;
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations(version text primary key,statements text[],name text);
alter table supabase_migrations.schema_migrations add column if not exists statements text[];
alter table supabase_migrations.schema_migrations add column if not exists name text;
do $$begin
 if exists(select 1 from supabase_migrations.schema_migrations) then raise exception 'Existing migration history detected: review before proceeding';end if;
end;$$;
`;
for(const file of files){
 const [version]=file.split('_');
 if(versions.has(version))throw new Error(`Duplicate migration version: ${version}`);
 versions.add(version);
 const sql=readFileSync(resolve(directory,file),'utf8').trim();
 const delimiter=`$kotoba_migration_${version}$`;
 if(sql.includes(delimiter))throw new Error(`SQL delimiter collision: ${file}`);
 const name=file.slice(version.length+1,-4);
 bundle+=`\n-- BEGIN ${file}\n${sql}\n-- END ${file}\n`;
 bundle+=`insert into supabase_migrations.schema_migrations(version,name,statements) values('${version}','${name}',array[${delimiter}${sql}${delimiter}]);\n`;
}
bundle+=`\n-- Server-side whitelist; no Auth account is created and no password is stored here.
select public.configure_private_owner('yzh72339@gmail.com');
commit;
select version,name from supabase_migrations.schema_migrations order by version;
`;
const target=resolve(root,'supabase/dashboard/02_fresh_project_migrations.sql');
mkdirSync(resolve(root,'supabase/dashboard'),{recursive:true});
writeFileSync(target,bundle,{mode:0o644});
console.log(`Prepared ${files.length} migrations in one fresh-project transaction: supabase/dashboard/02_fresh_project_migrations.sql`);
